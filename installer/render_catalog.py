"""Собрать данные мастера Inno Setup из ru_atc.voice.catalog и config.example.yaml.

Пишет installer/generated/:
  catalog.pas   — константы для радиокнопок и адресов загрузки
  files.iss     — строки [Files] с готовыми config.yaml
  config-*.yaml — шаблон config.example.yaml с выбранными моделью и голосом

Запуск из корня репозитория:  python installer/render_catalog.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ru_atc.setup_config import render_installed_config  # noqa: E402
from ru_atc.voice.catalog import SILERO_VOICES, VOSK_MODELS  # noqa: E402

OUT = Path(__file__).resolve().parent / "generated"


def pascal_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def pascal_array(name: str, values: list) -> str:
    if not values:
        raise ValueError(name)
    body = ",\n".join(f"    {pascal_str(v)}" for v in values)
    return f"  {name}: array[0..{len(values) - 1}] of String = (\n{body}\n  );"


def default_index(items: list) -> int:
    indexes = [i for i, item in enumerate(items) if item["default"]]
    if len(indexes) != 1:
        raise ValueError(f"нужен ровно один вариант по умолчанию, сейчас {indexes}")
    return indexes[0]


def render_catalog_pas() -> str:
    vosk_default = default_index(VOSK_MODELS)
    speaker_default = default_index(SILERO_VOICES)
    parts = [
        "const",
        f"  VoskCount = {len(VOSK_MODELS)};",
        f"  VoskDefault = {vosk_default};",
        f"  SpeakerCount = {len(SILERO_VOICES)};",
        f"  SpeakerDefault = {speaker_default};",
        pascal_array("VoskIds", [m["id"] for m in VOSK_MODELS]),
        pascal_array("VoskUrls", [m["url"] for m in VOSK_MODELS]),
        pascal_array("VoskCaptions", [m["caption"] for m in VOSK_MODELS]),
        pascal_array("SpeakerIds", [v["id"] for v in SILERO_VOICES]),
        pascal_array("SpeakerCaptions", [v["caption"] for v in SILERO_VOICES]),
        "",
    ]
    return "\n".join(parts)


def config_filename(vosk_id: str, speaker: str) -> str:
    return f"config-{vosk_id}-{speaker}.yaml"


def render_files_iss(names: list) -> str:
    lines = [
        "; Generated by installer/render_catalog.py — do not edit.",
    ]
    for name in names:
        lines.append(f'Source: "generated\\{name}"; Flags: dontcopy')
    lines.append("")
    return "\n".join(lines)


def write_bytes(path: Path, text: str, bom: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.replace("\r\n", "\n").encode("utf-8")
    if bom:
        data = b"\xef\xbb\xbf" + data
    path.write_bytes(data)


def build(out_dir: Path | None = None) -> dict:
    out = out_dir or OUT
    example = (ROOT / "config.example.yaml").read_text(encoding="utf-8")
    names = []
    files = {"catalog.pas": render_catalog_pas()}
    for model in VOSK_MODELS:
        for voice in SILERO_VOICES:
            name = config_filename(model["id"], voice["id"])
            names.append(name)
            files[name] = render_installed_config(example, model["id"], voice["id"])
    files["files.iss"] = render_files_iss(names)
    if out is not None:
        for name, text in files.items():
            write_bytes(out / name, text, bom=name.endswith(".pas"))
    return files


def main() -> None:
    # На бегуне Windows консоль часто cp1252, и русский print роняет скрипт.
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        except (OSError, ValueError):
            pass
    files = build(OUT)
    print(f"Записано {len(files)} файлов в {OUT}")


if __name__ == "__main__":
    main()
